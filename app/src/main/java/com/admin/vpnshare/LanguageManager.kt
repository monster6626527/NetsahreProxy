enum class AppLanguage(val code: String, val displayName: String, val isRtl: Boolean = false) {
    EN("en", "English"),
    AR("ar", "العربية", true),
    ES("es", "Español"),
    FR("fr", "Français")
}

object LanguageManager {
    var currentLanguage by mutableStateOf(AppLanguage.EN)
        private set

    fun setLanguage(language: AppLanguage, sharedPrefs: android.content.SharedPreferences) {
        currentLanguage = language
        sharedPrefs.edit().putString("app_language", language.code).apply()
    }

    fun init(sharedPrefs: android.content.SharedPreferences) {
        val saved = sharedPrefs.getString("app_language", "en") ?: "en"
        currentLanguage = AppLanguage.values().firstOrNull { it.code == saved } ?: AppLanguage.EN
    }

